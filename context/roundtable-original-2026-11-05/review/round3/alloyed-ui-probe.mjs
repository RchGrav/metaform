import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('crates/roundtable-web/assets/index.html','utf8');
const source=html.slice(html.indexOf('function table(id)'),html.indexOf('let pending = false;'));
const context=vm.createContext({state:{tables:new Map(),seen:new Set()},scheduleRender(){},loadPast(){}});
vm.runInContext(source,context);
let seq=0;
const send=(event,data)=>context.apply({seq:++seq,event,data:{table:'custom',...data}});
send('roundtable.opened',{objective:'test',topic:'test',judging:true,jev_configured:true,base_allowance:1024,seats:[{name:'Ada',harness:'fake',settings:{}}]});
const seat=context.state.tables.get('custom').seats.get('Ada');
assert.equal(seat.allowance,1024,'new seat uses custom base');
send('roundtable.floor',{seat:'Ada',allowance:3072});
send('roundtable.contribution',{seat:'Ada',accepted:false,reasons:['veto'],text:'x'});
assert.equal(seat.allowance,3072,'veto preserves bank');
send('roundtable.contribution',{seat:'Ada',accepted:true,text:'x'});
assert.equal(seat.allowance,1024,'acceptance resets custom base');
console.log('F16 PASS: custom-base initial, veto, acceptance');
const prompts=fs.readFileSync('crates/roundtable/src/prompts.rs','utf8');
assert.ok(!prompts.includes('privately'));
assert.match(prompts,/crate::rules::PROPOSAL_LIMIT/);
assert.match(fs.readFileSync('crates/roundtable/src/rules.rs','utf8'),/PROPOSAL_LIMIT: usize = 512/);
console.log('F17 PASS: private label absent; 512 bound retained');
